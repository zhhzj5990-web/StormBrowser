#pragma once
#include <QString>

class Logger {
public:
    // Инициализация перехватчика Qt сообщений
    static void init();

    // Получить путь к папке с логами (нужно для нашего меню)
    static QString getLogDir();

    // Записать стартовую системную информацию
    static void logSystemInfo();

    // Принудительная запись строки в лог в обход фильтра сообщений Qt.
    // Для намеренной диагностики (баннер запуска, служебные строки),
    // которая не является ошибкой и не должна проверяться на
    // "критическая ли это ошибка от своей функции", но всё равно
    // нужна в файле лога.
    static void logInfo(const QString& msg);
};